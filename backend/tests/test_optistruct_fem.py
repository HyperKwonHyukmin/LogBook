"""2026-11-23 — OptiStruct 입력(.fem, HyperMesh) 3D 미리보기: BDF 파서로 변환하고, kind 는 other(보기 전용) 그대로.
머리는 운영 보관소의 실제 .fem(E000099) 모양을 줄였다 — $$ 머리, OptiStruct 케이스 제어(SUBCASE, ANALYSIS), BEGIN BULK."""
import os

from app import models
from app.convert.job import enqueue_convert, model_paths, run_convert
from app.entries.locate import file_path
from app.ingest.rules import classify, has_model_view, is_abaqus_input, is_viewer_only
from app.storage.paths import to_long

FEM = """$$
$$ Optistruct Input Deck Generated by HyperMesh Version  : 2019.0.0.70
$$
$HMNAME LOADSTEP               2"Case1"       1
SUBCASE        2
  LABEL Case1
ANALYSIS STATICS
  SPC =        1
  LOAD =        2
BEGIN BULK
$HMNAME COMP                   1"PLATE"
GRID           1               0.0     0.0     0.0
GRID           2             100.0     0.0     0.0
GRID           3             100.0   100.0     0.0
GRID           4               0.0   100.0     0.0
GRID           5             200.0     0.0     0.0
GRID           6             200.0   100.0     0.0
CQUAD4         1       1       1       2       3       4
CQUAD4         2       1       2       5       6       3
CROD           3       2       1       5
PSHELL         1       1    12.0       1               1
PROD           2       1   100.0
MAT1           1 206000.0             0.3 7.85-09
SPC1           1  123456       1       4
FORCE          2       6       0     1.0     0.0     0.0  1000.0
ENDDATA
"""


def test_fem_is_viewer_only_model():
    assert classify("a.fem") == "other"
    assert has_model_view("other", "Case1.FEM") and is_viewer_only("x.fem") and not is_abaqus_input("x.fem")


def test_run_convert_fem_uses_bdf_parser_without_signature(db, storage, make_entry_file):
    _e, f = make_entry_file(name="3185_Case1.fem", kind="other", sha="e" * 64)
    p = file_path(db, storage, f)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as fh:
        fh.write(FEM.encode())
    assert enqueue_convert(db, f)
    db.commit()
    run_convert(db, storage, f)
    s = db.get(models.ModelSummary, f.id)
    assert s.state == "done" and s.error is None, s.error
    assert s.counts["CQUAD4"] == 2 and s.counts["CROD"] == 1 and s.counts["GRID"] == 6
    # 내용 서명(같은 BDF 막기)과 권상 판정은 BDF 전용 — CROD 가 있어도 Wire 모델로 보지 않는다
    assert s.sig_geometry is None and not s.lifting
    lbm, png = model_paths(storage, s.key)
    assert os.path.exists(to_long(lbm)) and os.path.exists(to_long(png))


def test_search_thumb_uses_fem_and_not_report_cover(client, db, storage, make_user, auth_headers, make_entry_file):
    make_user("A100001")
    e, f = make_entry_file(title="페엠 썸네일 시험", name="m.fem", kind="other")
    make_entry_file(entry=e, name="보고서.pdf", kind="report")
    db.commit()
    h = auth_headers("A100001")
    item = client.get("/api/search", params={"q": "페엠 썸네일"}, headers=h).json()["items"][0]
    assert item["thumb"] is None and item["cover"] is None   # 변환 전 — 보고서 첫 쪽이 아니라 아이콘
    db.add(models.ModelSummary(file_id=f.id, state="done", key="f" * 64, counts={"GRID": 4, "CQUAD4": 1}))
    db.commit()
    item = client.get("/api/search", params={"q": "페엠 썸네일"}, headers=h).json()["items"][0]
    assert item["thumb"]["file_id"] == f.id and item["cover"] is None
